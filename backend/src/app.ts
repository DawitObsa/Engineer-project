import express from "express";
import helmet from "helmet";
import cors from "cors";
import morgan from "morgan";
import rateLimit from "express-rate-limit";
import { ZodError } from "zod";
import { authRouter } from "./routes/auth.js";
import { projectRouter } from "./routes/projects.js";
import { documentRouter } from "./routes/documents.js";
import { eotRouter } from "./routes/eot.js";
import { correspondenceRouter } from "./routes/correspondence.js";
import { personnelRouter } from "./routes/personnel.js";
import { technicalSubmissionRouter } from "./routes/technicalSubmissions.js";
import { progressRouter } from "./routes/progress.js";
import { equipmentRouter, materialRouter, qualityRouter, recoveryRouter } from "./routes/operations.js";
import { organizationRouter, userRouter } from "./routes/users.js";
import { notificationRouter } from "./routes/notifications.js";
import { reportRouter } from "./routes/reports.js";
import { errorHandler } from "./utils/http.js";
import { env } from "./config/env.js";

export const app = express();
app.use(helmet());
app.use(cors({ origin: env.corsOrigin, credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use(morgan("combined"));
app.use("/api/v1/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: "draft-7", legacyHeaders: false, message: { success: false, error: { message: "Too many authentication attempts. Try again later." } } }));
app.get("/api/v1/health", (_req, res) => res.json({ success: true, data: { status: "ok" } }));
app.use("/api/v1/auth", authRouter);
app.use("/api/v1/projects", projectRouter);
app.use("/api/v1/documents", documentRouter);
app.use("/api/v1/eot", eotRouter);
app.use("/api/v1/correspondence", correspondenceRouter);
app.use("/api/v1/personnel", personnelRouter);
app.use("/api/v1/technical-submissions", technicalSubmissionRouter);
app.use("/api/v1/progress", progressRouter);
app.use("/api/v1/equipment", equipmentRouter);
app.use("/api/v1/materials", materialRouter);
app.use("/api/v1/recovery", recoveryRouter);
app.use("/api/v1/quality", qualityRouter);
app.use("/api/v1/users", userRouter);
app.use("/api/v1/organizations", organizationRouter);
app.use("/api/v1/notifications", notificationRouter);
app.use("/api/v1/reports", reportRouter);
app.use((error: Error, _req: express.Request, res: express.Response, next: express.NextFunction) => { if (error instanceof ZodError) return res.status(400).json({ success: false, error: { message: "Request validation failed", details: error.flatten() } }); next(error); });
app.use(errorHandler);
